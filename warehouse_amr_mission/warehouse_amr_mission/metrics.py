"""Mission metric recording, aggregation and README table rendering.

Pure standard library so CI can summarise benchmark output without ROS.

The point of this module: every number that ends up in the README is produced
by ``summarize()`` from a committed JSONL/JSON artifact. If a number cannot be
regenerated by ``make bench``, it does not go in the README.
"""

from __future__ import annotations

import json
import os
import statistics
from dataclasses import asdict, dataclass
from typing import Dict, Iterable, List, Optional, Sequence


@dataclass
class MissionResult:
    mission_id: str
    outcome: str            # succeeded | aborted | timeout
    duration_s: float
    nav_goals: int = 0
    nav_failures: int = 0
    retries_used: int = 0
    started_at: float = 0.0
    ended_at: float = 0.0
    note: str = ''

    def to_dict(self) -> Dict:
        return asdict(self)

    @classmethod
    def from_dict(cls, raw: Dict) -> 'MissionResult':
        known = {f: raw[f] for f in cls.__dataclass_fields__ if f in raw}
        return cls(**known)


class JsonlRecorder:
    """Append-only JSONL sink. One row per finished mission (or goal)."""

    def __init__(self, path: str) -> None:
        self.path = path
        directory = os.path.dirname(os.path.abspath(path))
        if directory:
            os.makedirs(directory, exist_ok=True)
        self._fh = open(path, 'a', encoding='utf-8')

    def write(self, row) -> None:
        payload = row.to_dict() if isinstance(row, MissionResult) else row
        self._fh.write(json.dumps(payload, ensure_ascii=False) + '\n')
        self._fh.flush()

    def close(self) -> None:
        if not self._fh.closed:
            self._fh.close()

    def __enter__(self) -> 'JsonlRecorder':
        return self

    def __exit__(self, *exc) -> None:
        self.close()


def percentile(values: Sequence[float], p: float) -> float:
    """Linear-interpolated percentile (``p`` in [0, 100]). Empty -> 0.0."""
    if not values:
        return 0.0
    if not 0.0 <= p <= 100.0:
        raise ValueError('p must be within [0, 100]')
    ordered = sorted(values)
    if len(ordered) == 1:
        return float(ordered[0])
    rank = (len(ordered) - 1) * (p / 100.0)
    lower = int(rank)
    upper = min(lower + 1, len(ordered) - 1)
    weight = rank - lower
    return float(ordered[lower] * (1.0 - weight) + ordered[upper] * weight)


def summarize(results: Iterable, success_outcome: str = 'succeeded') -> Dict:
    rows = [r if isinstance(r, MissionResult) else MissionResult.from_dict(r) for r in results]
    durations = [r.duration_s for r in rows]
    successes = sum(1 for r in rows if r.outcome == success_outcome)
    failures = [r for r in rows if r.outcome != success_outcome]

    reasons: Dict[str, int] = {}
    for row in failures:
        key = row.note or row.outcome
        reasons[key] = reasons.get(key, 0) + 1

    total = len(rows)
    return {
        'missions': total,
        'succeeded': successes,
        'failed': total - successes,
        'success_rate': (successes / total) if total else 0.0,
        'duration_mean_s': statistics.fmean(durations) if durations else 0.0,
        'duration_p50_s': percentile(durations, 50.0),
        'duration_p95_s': percentile(durations, 95.0),
        'duration_max_s': max(durations) if durations else 0.0,
        'nav_goals_mean': statistics.fmean([r.nav_goals for r in rows]) if rows else 0.0,
        'retries_total': sum(r.retries_used for r in rows),
        'failure_reasons': reasons,
    }


def load_jsonl(path: str) -> List[MissionResult]:
    rows: List[MissionResult] = []
    if not os.path.exists(path):
        return rows
    with open(path, encoding='utf-8') as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(MissionResult.from_dict(json.loads(line)))
    return rows


def write_summary(path: str, rows: Sequence, meta: Optional[Dict] = None) -> Dict:
    """Persist ``{meta, summary, rows}`` so a benchmark run is reproducible."""
    payload = {
        'meta': meta or {},
        'summary': summarize(rows),
        'rows': [r.to_dict() if isinstance(r, MissionResult) else r for r in rows],
    }
    directory = os.path.dirname(os.path.abspath(path))
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as fh:
        json.dump(payload, fh, ensure_ascii=False, indent=2)
        fh.write('\n')
    return payload


def render_table(summary: Dict, meta: Optional[Dict] = None) -> str:
    """Markdown table used inside the README benchmark block."""
    meta = meta or {}
    reasons = summary.get('failure_reasons') or {}
    reasons_text = ', '.join(f'{k} x{v}' for k, v in sorted(reasons.items())) or '-'

    lines = [
        '| 指标 / metric | 值 / value |',
        '| --- | --- |',
        f"| 任务数 missions | {summary['missions']} |",
        f"| 成功率 success rate | {summary['success_rate'] * 100:.1f} % "
        f"({summary['succeeded']}/{summary['missions']}) |",
        f"| 单任务耗时 mean | {summary['duration_mean_s']:.1f} s |",
        f"| 单任务耗时 P50 | {summary['duration_p50_s']:.1f} s |",
        f"| 单任务耗时 P95 | {summary['duration_p95_s']:.1f} s |",
        f"| 导航目标数/任务 mean | {summary['nav_goals_mean']:.2f} |",
        f"| 重试次数合计 retries | {summary['retries_total']} |",
        f'| 失败原因 failure reasons | {reasons_text} |',
    ]
    if meta.get('sim') or meta.get('hardware'):
        lines.append(f"| 环境 environment | {meta.get('sim') or meta.get('hardware')} |")
    if meta.get('git_sha'):
        lines.append(f"| 版本 commit | `{meta['git_sha'][:8]}` |")
    if meta.get('timestamp'):
        lines.append(f"| 采集时间 collected | {meta['timestamp']} |")
    return '\n'.join(lines)


def render_readme_block(summary: Dict, meta: Optional[Dict] = None) -> str:
    return ('<!-- BENCH:START -->\n' + render_table(summary, meta) + '\n<!-- BENCH:END -->')
